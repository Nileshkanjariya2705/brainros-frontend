/**
 * Resolves the union of permissions from a user's roles and any custom backend permissions.
 */
export const computeEffectivePermissions = (
  userRoles: string[] = [],
  customPermissions: string[] = [],
): string[] => {
  const rolePerms = userRoles.flatMap((role) => DEFAULT_ROLE_PERMISSIONS[role] || []);
  const allPerms = new Set([...rolePerms, ...customPermissions]);
  return Array.from(allPerms);
};
